{
    uint32_t g_vuTraceProgramStart = 0;
    int g_vuTraceRemaining = -1;
    uint32_t g_vuTracePc = 0xFFFFFFFFu;
    int64_t g_vuTraceIndex = -2;
}

void VU1Interpreter::finishXgkick()
{
    if (!m_xgkick.active)
        return;
    {
        static bool s_reported = false;
        if (!s_reported && std::getenv("PS2X_VU1_FIND"))
        {
            for (uint32_t off = 0; off + 16u <= m_xgkick.totalBytes; off += 16u)
            {
                uint64_t lo, hi;
                std::memcpy(&lo, m_xgkick.packet.data() + off, 8);
                std::memcpy(&hi, m_xgkick.packet.data() + off + 8, 8);
                if (lo == 0x4bull && hi == 0x4bull)
                {
                    s_reported = true;
                    std::printf("[vu1-find] exec=%llu program start pc=0x%x kick src=0x%x qword=%u\n", static_cast<unsigned long long>(g_vuExecCount), g_vuTraceProgramStart,
                                m_xgkick.sourceAddress, off / 16u);
                    break;
                }
            }
        }
    }

    if (m_activeMemory)
        m_activeMemory->submitGifPacket(GifPathId::Path1, m_xgkick.packet.data(), m_xgkick.totalBytes);
    else if (m_activeGs)
        m_activeGs->processGIFPacket(m_xgkick.packet.data(), m_xgkick.totalBytes);
    m_xgkick.active = false;
}

void VU1Interpreter::startXgkick(uint32_t qwordAddress)
{
    if (m_unit != Unit::VU1 || !m_activeVuData || m_activeVuDataSize < 16u)
        return;

    const uint32_t sourceAddress = (qwordAddress * 16u) % m_activeVuDataSize;
    m_xgkick = {};
    m_xgkick.active = true;
    m_xgkick.sourceAddress = sourceAddress;
    m_xgkick.cycleCredit = 1u; // XGKICK's issue cycle counts toward PATH1.
    m_xgkick.issueCycle = m_cycle;
}

void VU1Interpreter::advanceOneCycle()
{
    ++m_cycle;
    m_state.cycles = m_cycle;
    // LSU commits become visible at the cycle boundary before PATH1 consumes
    // its next qword from VU memory.
    commitReadyPipelines();
    progressXgkick();
}

void VU1Interpreter::advanceTo(uint64_t targetCycle)
{
    while (m_cycle < targetCycle)
        advanceOneCycle();
}

bool VU1Interpreter::pipelinesPending() const
{
    if (m_fdiv.valid || m_xgkick.active)
        return true;
    for (const ScalarPipelineEntry &entry : m_efu)
        if (entry.valid)
            return true;
    for (const FlagPipelineEntry &entry : m_flagPipeline)
        if (entry.valid)
            return true;
    for (const PendingStore &store : m_storePipeline)
        if (store.valid)
            return true;
    for (const PendingVfWrite &write : m_vfWritePipeline)
        if (write.valid)
            return true;
    for (const PendingViWrite &write : m_viWritePipeline)
        if (write.valid)
            return true;
    for (const PendingAccWrite &write : m_accWritePipeline)
        if (write.valid)
            return true;
    return false;
}

void VU1Interpreter::flushPipelines()
{
    while (pipelinesPending())
        advanceOneCycle();
}

uint64_t VU1Interpreter::calculatePairReadyCycle(const DecodedInstructionPair &decoded) const
{
    uint64_t ready = m_cycle;
    const InstructionUsage *usages[2] = {
        &decoded.upperUsage,
        &decoded.lowerUsage};
    for (const InstructionUsage *usage : usages)
    {
        if (!usage)
            continue;
        for (uint32_t index = 0; index < usage->vfReadCount; ++index)
        {
            const VfAccess &access = usage->vfRead[index];
            for (uint32_t component = 0; component < 4u; ++component)
            {
                if ((access.lanes & laneForComponent(component)) != 0u)
                    ready = std::max(ready, m_vfReady[access.reg][component]);
            }
        }
        for (uint32_t bits = static_cast<uint32_t>(usage->viRead) & 0xFFFEu; bits != 0u; bits &= bits - 1u)
        {
            const uint32_t reg = static_cast<uint32_t>(std::countr_zero(bits));
            if (reg < m_viReady.size())
                ready = std::max(ready, m_viReady[reg]);
        }
        for (uint32_t component = 0; component < 4u; ++component)
        {
            if ((usage->accRead & laneForComponent(component)) != 0u)
                ready = std::max(ready, m_accReady[component]);
        }
    }

    if (decoded.lowerUsage.pipeline == PipelineFdiv && m_fdiv.valid)
        ready = std::max(ready, m_fdiv.readyCycle);
    if (decoded.lowerUsage.pipeline == PipelineEfu)
        ready = std::max(ready, m_efuResourceReady);
    if (decoded.lowerUsage.waitQ && m_fdiv.valid)
        ready = std::max(ready, m_fdiv.readyCycle);
    if (decoded.lowerUsage.waitP)
    {
        for (const ScalarPipelineEntry &entry : m_efu)
            if (entry.valid)
                ready = std::max(ready, entry.readyCycle);
    }
    if (decoded.lowerUsage.pipeline == PipelineXgkick && m_xgkick.active)
        ready = std::max(ready, m_cycle + 1u);
    return ready;
}

void VU1Interpreter::markPairWrites(const DecodedInstructionPair &decoded)
{
    const VfAccess lowerWrite = decoded.lowerUsage.vfWrite;
    if (lowerWrite.reg != 0u &&
        decoded.suppressedLowerVf != lowerWrite.reg)
    {
        const uint32_t latency = decoded.lowerUsage.vfLatency != 0u
                                     ? decoded.lowerUsage.vfLatency
                                     : decoded.lowerUsage.latency;
        for (uint32_t component = 0; component < 4u; ++component)
        {
            if ((lowerWrite.lanes & laneForComponent(component)) != 0u)
                m_vfReady[lowerWrite.reg][component] = m_cycle + latency;
        }
    }

    const VfAccess upperWrite = decoded.upperUsage.vfWrite;
    if (upperWrite.reg != 0u)
    {
        const uint32_t latency = decoded.upperUsage.vfLatency != 0u
                                     ? decoded.upperUsage.vfLatency
                                     : decoded.upperUsage.latency;
        for (uint32_t component = 0; component < 4u; ++component)
        {
            if ((upperWrite.lanes & laneForComponent(component)) != 0u)
                m_vfReady[upperWrite.reg][component] = m_cycle + latency;
        }
    }

    for (uint32_t reg = 1; reg < m_viReady.size(); ++reg)
    {
        if ((decoded.lowerUsage.viWrite & (1u << reg)) != 0u)
            m_viReady[reg] = m_cycle + (decoded.lowerUsage.viLatency != 0u ? decoded.lowerUsage.viLatency : decoded.lowerUsage.latency);
    }
    for (uint32_t component = 0; component < 4u; ++component)
    {
        if ((decoded.upperUsage.accWrite & laneForComponent(component)) != 0u)
            m_accReady[component] = m_cycle + kAccForwardLatency;
    }
}

VU1Interpreter::InstructionUsage VU1Interpreter::decodeUpperUsage(uint32_t upper) const
{
    InstructionUsage usage;
    usage.pipeline = PipelineFmac;
    usage.latency = kFmacLatency;

    const uint8_t op = static_cast<uint8_t>(upper & 0x3Fu);
    const uint8_t dest = DEST(upper);
    const uint8_t fs = FS(upper);
    const uint8_t ft = FT(upper);
    const uint8_t fd = FD(upper);

    if (op <= 0x2Fu)
    {
        addVfRead(usage, fs, dest);
        addVfWrite(usage, fd, dest);
        if (op <= 0x1Bu)
            addVfRead(usage, ft, laneForComponent(op & 3u));
        else if (op >= 0x28u)
            addVfRead(usage, ft, op == 0x2Eu ? 0xEu : dest);
        if (op == 0x08u || op == 0x09u || op == 0x0Au || op == 0x0Bu ||
            op == 0x0Cu || op == 0x0Du || op == 0x0Eu || op == 0x0Fu ||
            op == 0x21u || op == 0x23u || op == 0x25u || op == 0x27u ||
            op == 0x29u || op == 0x2Du || op == 0x2Eu)
        {
            usage.accRead = dest;
        }
        return usage;
    }

    if (op >= 0x3Cu)
    {
        const uint8_t special = static_cast<uint8_t>((upper & 3u) | ((upper >> 4) & 0x7Cu));
        const bool writesAcc =
            special <= 0x0Fu ||
            (special >= 0x18u && special <= 0x1Cu) ||
            special == 0x1Eu ||
            (special >= 0x20u && special <= 0x2Au) ||
            (special >= 0x2Cu && special <= 0x2Eu);
        if (writesAcc)
        {
            addVfRead(usage, fs, dest);
            if (special <= 0x1Bu)
                addVfRead(usage, ft, laneForComponent(special & 3u));
            else if ((special >= 0x28u && special <= 0x2Eu))
                addVfRead(usage, ft, special == 0x2Eu ? 0xEu : dest);
            usage.accWrite = dest;
            if ((special >= 0x08u && special <= 0x0Fu) ||
                special == 0x21u || special == 0x23u || special == 0x25u ||
                special == 0x27u || special == 0x29u || special == 0x2Du)
            {
                usage.accRead = dest;
            }
        }
        else if (special >= 0x10u && special <= 0x17u)
        {
            addVfRead(usage, fs, dest);
            addVfWrite(usage, ft, dest);
        }
        else if (special == 0x1Du)
        {
            addVfRead(usage, fs, dest);
            addVfWrite(usage, ft, dest);
        }
        else if (special == 0x1Fu)
        {
            addVfRead(usage, fs, 0xEu);
            addVfRead(usage, ft, 0x1u);
            usage.writesClip = true;
        }
        else if (special != 0x2Fu && special != 0x30u)
        {
            usage.reserved = true;
        }
        return usage;
    }

    usage.reserved = true;
    return usage;
}

VU1Interpreter::InstructionUsage VU1Interpreter::decodeLowerUsage(uint32_t lower) const
{
    InstructionUsage usage;
    if (lower == 0u || lower == 0x8000033Cu)
        return usage;

    const uint8_t opHi = static_cast<uint8_t>((lower >> 25) & 0x7Fu);
    const uint8_t vfT = FT(lower);
    const uint8_t vfS = FS(lower);
    const uint8_t viT = VIT(lower);
    const uint8_t viS = VIS(lower);
    const uint8_t viD = VID(lower);
    const uint8_t dest = DEST(lower);
    auto readVi = [&](uint8_t reg)
    {
        if (reg != 0u)
            usage.viRead |= static_cast<uint16_t>(1u << reg);
    };
    auto writeVi = [&](uint8_t reg)
    {
        if (reg != 0u)
            usage.viWrite |= static_cast<uint16_t>(1u << reg);
    };

    switch (opHi)
    {
    case 0x00:
        usage.pipeline = PipelineLsu;
        usage.latency = 4u;
        readVi(viS);
        addVfWrite(usage, vfT, dest);
        return usage;
    case 0x01:
        usage.pipeline = PipelineLsu;
        usage.latency = 1u;
        readVi(viT);
        addVfRead(usage, vfS, dest);
        return usage;
    case 0x04:
        usage.pipeline = PipelineLsu;
        usage.latency = 4u;
        readVi(viS);
        writeVi(viT);
        return usage;
    case 0x05:
        usage.pipeline = PipelineLsu;
        usage.latency = 1u;
        readVi(viS);
        readVi(viT);
        return usage;
    case 0x08:
    case 0x09:
        usage.pipeline = PipelineIalu;
        usage.latency = 1u;
        usage.delaysNextBranchRead = true;
        readVi(viS);
        writeVi(viT);
        return usage;
    case 0x10:
    case 0x12:
    case 0x13:
        usage.pipeline = PipelineIalu;
        usage.latency = 1u;
        usage.readsClip = true;
        writeVi(1u);
        return usage;
    case 0x11:
        usage.pipeline = PipelineFmac;
        usage.latency = kFmacLatency;
        usage.writesClip = true;
        return usage;
    case 0x14:
    case 0x16:
    case 0x17:
        usage.pipeline = PipelineIalu;
        usage.latency = 1u;
        writeVi(viT);
        return usage;
    case 0x15:
        usage.pipeline = PipelineFmac;
        usage.latency = kFmacLatency;
        return usage;
    case 0x18:
    case 0x1A:
    case 0x1B:
        usage.pipeline = PipelineIalu;
        usage.latency = 1u;
        readVi(viS);
        writeVi(viT);
        return usage;
    case 0x1C:
        usage.pipeline = PipelineIalu;
        usage.latency = 1u;
        usage.readsClip = true;
        writeVi(viT);
        return usage;
    case 0x20:
        usage.pipeline = PipelineBranch;
        return usage;
    case 0x21:
        usage.pipeline = PipelineBranch;
        usage.latency = 1u;
        writeVi(viT);
        return usage;
    case 0x24:
        usage.pipeline = PipelineBranch;
        readVi(viS);
        return usage;
    case 0x25:
        usage.pipeline = PipelineBranch;
        usage.latency = 1u;
        readVi(viS);
        writeVi(viT);
        return usage;
    case 0x28:
    case 0x29:
        usage.pipeline = PipelineBranch;
        readVi(viS);
        readVi(viT);
        return usage;
    case 0x2C:
    case 0x2D:
    case 0x2E:
    case 0x2F:
        usage.pipeline = PipelineBranch;
        readVi(viS);
        return usage;
    case 0x40:
        break;
    default:
        usage.reserved = true;
        return usage;
    }

    const uint8_t direct = static_cast<uint8_t>(lower & 0x3Fu);
    if (direct == 0x30u || direct == 0x31u || direct == 0x34u || direct == 0x35u)
    {
        usage.pipeline = PipelineIalu;
        usage.latency = 1u;
        usage.delaysNextBranchRead = true;
        readVi(viS);
        readVi(viT);
        writeVi(viD);
        return usage;
    }
    if (direct == 0x32u)
    {
        usage.pipeline = PipelineIalu;
        usage.latency = 1u;
        usage.delaysNextBranchRead = true;
        readVi(viS);
        writeVi(viT);
        return usage;
    }
    if (direct < 0x3Cu)
    {
        usage.reserved = true;
        return usage;
    }

    const uint8_t special = static_cast<uint8_t>((lower & 3u) | ((lower >> 4) & 0x7Cu));
    switch (special)
    {
    case 0x30:
    case 0x31:
        usage.pipeline = PipelineFmac;
        usage.latency = 4u;
        addVfRead(usage, vfS, special == 0x31u ? 0xFu : dest);
        addVfWrite(usage, vfT, dest);
        break;
    case 0x34:
    case 0x36:
        usage.pipeline = PipelineLsu;
        usage.latency = 4u;
        usage.viLatency = 1u;
        usage.delaysNextBranchRead = true;
        readVi(viS);
        writeVi(viS);
        addVfWrite(usage, vfT, dest);
        break;
    case 0x35:
    case 0x37:
        usage.pipeline = PipelineLsu;
        usage.latency = 1u;
        usage.delaysNextBranchRead = true;
        readVi(viT);
        writeVi(viT);
        addVfRead(usage, vfS, dest);
        break;
    case 0x38:
        usage.pipeline = PipelineFdiv;
        usage.latency = 7u;
        addVfRead(usage, vfS, laneForComponent((lower >> 21) & 3u));
        addVfRead(usage, vfT, laneForComponent((lower >> 23) & 3u));
        break;
    case 0x39:
        usage.pipeline = PipelineFdiv;
        usage.latency = 7u;
        addVfRead(usage, vfT, laneForComponent((lower >> 23) & 3u));
        break;
    case 0x3A:
        usage.pipeline = PipelineFdiv;
        usage.latency = 13u;
        addVfRead(usage, vfS, laneForComponent((lower >> 21) & 3u));
        addVfRead(usage, vfT, laneForComponent((lower >> 23) & 3u));
        break;
    case 0x3B:
        usage.pipeline = PipelineFdiv;
        usage.waitQ = true;
        break;
    case 0x3C:
        usage.pipeline = PipelineIalu;
        usage.latency = 1u;
        usage.delaysNextBranchRead = true;
        addVfRead(usage, vfS, laneForComponent((lower >> 21) & 3u));
        writeVi(viT);
        break;
    case 0x3D:
        usage.pipeline = PipelineFmac;
        usage.latency = 4u;
        readVi(viS);
        addVfWrite(usage, vfT, dest);
        break;
    case 0x3E:
        usage.pipeline = PipelineLsu;
        usage.latency = 4u;
        readVi(viS);
        writeVi(viT);
        break;
    case 0x3F:
        usage.pipeline = PipelineLsu;
        usage.latency = 1u;
        readVi(viS);
        readVi(viT);
        break;
    case 0x40:
    case 0x41:
        usage.pipeline = PipelineFmac;
        usage.latency = 4u;
        addVfWrite(usage, vfT, dest);
        break;
    case 0x42:
    case 0x43:
        usage.pipeline = PipelineIalu;
        usage.latency = 1u;
        addVfRead(usage, vfS, laneForComponent((lower >> 21) & 3u));
        break;
    case 0x64:
        if (m_unit == Unit::VU0)
        {
            usage.reserved = true;
            break;
        }
        usage.pipeline = PipelineFmac;
        usage.latency = 4u;
        addVfWrite(usage, vfT, dest);
        break;
    case 0x68:
    case 0x69:
        usage.pipeline = PipelineIalu;
        usage.latency = 1u;
        writeVi(viT);
        break;
    case 0x6C:
        if (m_unit == Unit::VU0)
        {
            usage.reserved = true;
            break;
        }
        usage.pipeline = PipelineXgkick;
        usage.latency = 2u;
        readVi(viS);
        break;
    case 0x70:
    case 0x71:
    case 0x72:
    case 0x73:
    case 0x74:
    case 0x75:
    case 0x76:
    case 0x77:
    case 0x78:
    case 0x79:
    case 0x7A:
    case 0x7C:
    case 0x7D:
        if (m_unit == Unit::VU0)
        {
            usage.reserved = true;
            break;
        }
        usage.pipeline = PipelineEfu;
        switch (special)
        {
        case 0x70:
            usage.latency = 11u;
            break;
        case 0x71:
        case 0x72:
        case 0x77:
            usage.latency = 18u;
            break;
        case 0x73:
            usage.latency = 24u;
            break;
        case 0x74:
        case 0x75:
        case 0x7C:
            usage.latency = 54u;
            break;
        case 0x76:
        case 0x78:
        case 0x7A:
            usage.latency = 12u;
            break;
        case 0x79:
            usage.latency = 29u;
            break;
        case 0x7D:
            usage.latency = 44u;
            break;
        default:
            break;
        }
        if (special >= 0x70u && special <= 0x73u)
            addVfRead(usage, vfS, 0xEu);
        else if (special == 0x74u)
            addVfRead(usage, vfS, 0xCu);
        else if (special == 0x75u)
            addVfRead(usage, vfS, 0xAu);
        else if (special == 0x76u)
            addVfRead(usage, vfS, 0xFu);
        else
            addVfRead(usage, vfS, laneForComponent((lower >> 21) & 3u));
        break;
    case 0x7B:
        if (m_unit == Unit::VU0)
        {
            usage.reserved = true;
            break;
        }
        usage.pipeline = PipelineEfu;
        usage.waitP = true;
        break;
    default:
        usage.reserved = true;
        break;
    }
    return usage;
}

VU1Interpreter::DecodedInstructionPair VU1Interpreter::decodeInstructionPair(const uint8_t *vuCode, uint32_t pc) const
{
    DecodedInstructionPair decoded;
    std::memcpy(&decoded.lower, vuCode + pc, sizeof(decoded.lower));
    std::memcpy(&decoded.upper, vuCode + pc + sizeof(decoded.lower), sizeof(decoded.upper));
    decoded.iBit = (decoded.upper & 0x80000000u) != 0u;
    decoded.eBit = (decoded.upper & 0x40000000u) != 0u;
    decoded.mBit = (decoded.upper & 0x20000000u) != 0u;
    decoded.dBit = (decoded.upper & 0x10000000u) != 0u;
    decoded.tBit = (decoded.upper & 0x08000000u) != 0u;
    decoded.upperUsage = decodeUpperUsage(decoded.upper);
    if (!decoded.iBit)
        decoded.lowerUsage = decodeLowerUsage(decoded.lower);

    const uint8_t upperWriteReg = decoded.upperUsage.vfWrite.reg;
    if (upperWriteReg != 0u && (vfReadLanes(decoded.lowerUsage, upperWriteReg) != 0u || decoded.lowerUsage.vfWrite.reg == upperWriteReg))
    {
        decoded.upperVfShadowReg = upperWriteReg;
        if (decoded.lowerUsage.vfWrite.reg == upperWriteReg)
            decoded.suppressedLowerVf = upperWriteReg;
    }
    return decoded;
}

void VU1Interpreter::rebuildDecodedCodeCache(const uint8_t *vuCode, uint32_t codeSize,
                                             const PS2Memory *memory, uint64_t generation)
{
    const uint32_t pairCount = std::min<uint32_t>(codeSize / 8u, kMaxDecodedPairs);
    for (uint32_t i = 0; i < pairCount; ++i)
        m_decodedCodeCache[i] = decodeInstructionPair(vuCode, i * 8u);

    m_cachedVuCode = vuCode;
    m_cachedMemory = memory;
    m_cachedCodeSize = codeSize;
    m_cachedCodeGeneration = generation;
    m_decodedCodeCacheValid = true;
}

VU1Interpreter::DecodedInstructionPair VU1Interpreter::getDecodedInstructionPairForPc(
    const uint8_t *vuCode, uint32_t codeSize, PS2Memory *memory, uint32_t pc)
{
    if ((pc & 7u) != 0u)
        return decodeInstructionPair(vuCode, pc);

    const bool trackedVu1Code = memory != nullptr &&
                                ((m_unit == Unit::VU1 && vuCode == memory->getVU1Code()) ||
                                 (m_unit == Unit::VU0 && vuCode == memory->getVU0Code()));
    if (!trackedVu1Code)
        return decodeInstructionPair(vuCode, pc);

    const uint64_t generation = m_unit == Unit::VU1 ? memory->getVU1CodeGeneration() : memory->getVU0CodeGeneration();
    if (!m_decodedCodeCacheValid ||
        m_cachedVuCode != vuCode ||
        m_cachedMemory != memory ||
        m_cachedCodeSize != codeSize ||
        m_cachedCodeGeneration != generation)
    {
        rebuildDecodedCodeCache(vuCode, codeSize, memory, generation);
    }
    const uint32_t pairIndex = pc / 8u;
    if (pairIndex >= kMaxDecodedPairs)
        return decodeInstructionPair(vuCode, pc);
    return m_decodedCodeCache[pairIndex];
}

void VU1Interpreter::reportReservedInstruction(bool upper, uint32_t instruction)
{
    RUNTIME_ERROR(
        "[VU" << (m_unit == Unit::VU1 ? "1" : "0")
              << " reserved " << (upper ? "upper" : "lower")
              << "] cycle=" << m_cycle
              << " pc=0x" << std::hex << m_state.pc
              << " instruction=0x" << instruction
              << std::dec << '\n');
    m_stopRequested = true;
}

namespace ps2vu1n { extern uint64_t g_nativeRuns, g_nativeFallbacks, g_nativeMisses, g_nativeCycles; }
bool ps2vu1nTryRun(VU1State &state, uint8_t *vuData, uint32_t dataSize, PS2Memory *memory,
                   uint64_t codeHash, uint32_t maxCycles, bool &ended);

namespace
{
    // Identifies the resident VU1 microcode image (rehashed only when MPG changes it) and, with
    // PS2X_VU_DUMP=<dir>, writes each distinct image + entry point for the offline VU1 recompiler.
    uint64_t g_vu1CodeGen = ~0ull;
    uint64_t g_vu1CodeHash = 0;
    uint64_t g_vu1HashChanges = 0;

    void noteVu1Program(const uint8_t *code, uint32_t size, uint64_t generation, uint32_t pc)
    {
        if (generation != g_vu1CodeGen)
        {
            g_vu1CodeGen = generation;
            uint64_t h = 1469598103934665603ull;
            for (uint32_t i = 0; i < size; i += 8)
            {
                uint64_t w;
                std::memcpy(&w, code + i, 8);
                h = (h ^ w) * 1099511628211ull;
                h ^= h >> 29;
            }
            if (h != g_vu1CodeHash)
                ++g_vu1HashChanges;
            g_vu1CodeHash = h;
        }
        static const char *s_dumpDir = std::getenv("PS2X_VU_DUMP");
        if (!s_dumpDir || !*s_dumpDir)
            return;
        static std::vector<std::pair<uint64_t, uint32_t>> s_seen;
        static std::vector<uint64_t> s_images;
        const auto key = std::make_pair(g_vu1CodeHash, pc);
        if (std::find(s_seen.begin(), s_seen.end(), key) != s_seen.end())
            return;
        s_seen.push_back(key);
        char path[1024];
        if (std::find(s_images.begin(), s_images.end(), g_vu1CodeHash) == s_images.end())
        {
            s_images.push_back(g_vu1CodeHash);
            std::snprintf(path, sizeof(path), "%s/vu1_%016llx.bin", s_dumpDir, static_cast<unsigned long long>(g_vu1CodeHash));
            if (FILE *f = std::fopen(path, "wb"))
            {
                std::fwrite(code, 1, size, f);
                std::fclose(f);
            }
        }
        std::snprintf(path, sizeof(path), "%s/vu1_entries.txt", s_dumpDir);
        if (FILE *f = std::fopen(path, "a"))
        {
            std::fprintf(f, "%016llx %04x\n", static_cast<unsigned long long>(g_vu1CodeHash), pc);
            std::fclose(f);
        }
    }
}

namespace
{
    // PS2X_VU1_VERIFY=1: run the native program on a snapshot (no GIF output), then the interpreter
    // on the same input (its results are kept), and report register/memory mismatches.
    template <typename InterpFn>
    bool vu1VerifyNative(VU1State &st, uint8_t *mem, uint32_t size, uint64_t hash, uint32_t maxCycles, InterpFn &&interp)
    {
        static const bool s_on = std::getenv("PS2X_VU1_VERIFY") != nullptr;
        if (!s_on)
            return false;
        // PS2X_VU1_VERIFY=<seconds>: only start verifying after that long (the interpreter is slow).
        static const double s_startSec = std::atof(std::getenv("PS2X_VU1_VERIFY"));
        static const auto s_boot = std::chrono::steady_clock::now();
        if (s_startSec > 0.0 && std::chrono::duration<double>(std::chrono::steady_clock::now() - s_boot).count() < s_startSec)
            return false;
        const VU1State saved = st;
        const std::vector<uint8_t> m0(mem, mem + size);
        const uint32_t entry = st.pc;
        bool ended = false;
        if (!ps2vu1nTryRun(st, mem, size, nullptr, hash, maxCycles, ended) || !ended)
        {
            st = saved;
            std::memcpy(mem, m0.data(), size);
            return false;
        }
        const VU1State nat = st;
        const std::vector<uint8_t> m1(mem, mem + size);
        st = saved;
        std::memcpy(mem, m0.data(), size);
        interp();

        static int s_reports = 0;
        static uint64_t s_checked = 0, s_bad = 0;
        ++s_checked;
        std::string diff;
        char buf[160];
        for (int r = 1; r < 32; ++r)
            if (std::memcmp(nat.vf[r], st.vf[r], 16) != 0 && diff.size() < 600)
            {
                uint32_t a[4], b[4];
                std::memcpy(a, nat.vf[r], 16);
                std::memcpy(b, st.vf[r], 16);
                std::snprintf(buf, sizeof(buf), " vf%d n=[%08x %08x %08x %08x] i=[%08x %08x %08x %08x]", r, a[0], a[1], a[2], a[3], b[0], b[1], b[2], b[3]);
                diff += buf;
            }
        for (int r = 1; r < 16; ++r)
            if ((nat.vi[r] & 0xFFFF) != (st.vi[r] & 0xFFFF))
            {
                std::snprintf(buf, sizeof(buf), " vi%d n=%04x i=%04x", r, nat.vi[r] & 0xFFFF, st.vi[r] & 0xFFFF);
                diff += buf;
            }
        if (std::memcmp(nat.acc, st.acc, 16) != 0)
            diff += " acc";
        if (nat.pc != st.pc)
        {
            std::snprintf(buf, sizeof(buf), " pc n=%x i=%x", nat.pc, st.pc);
            diff += buf;
        }
        uint32_t memDiff = 0, firstQw = 0xFFFFFFFFu;
        for (uint32_t q = 0; q < size; q += 16)
            if (std::memcmp(m1.data() + q, mem + q, 16) != 0)
            {
                if (firstQw == 0xFFFFFFFFu)
                    firstQw = q / 16;
                ++memDiff;
            }
        if (memDiff)
        {
            uint32_t a[4], b[4];
            std::memcpy(a, m1.data() + firstQw * 16, 16);
            std::memcpy(b, mem + firstQw * 16, 16);
            std::snprintf(buf, sizeof(buf), " mem %u qw first=%x n=[%08x %08x %08x %08x] i=[%08x %08x %08x %08x]", memDiff, firstQw,
                          a[0], a[1], a[2], a[3], b[0], b[1], b[2], b[3]);
            diff += buf;
        }
        static const bool s_memOnly = std::getenv("PS2X_VU1_VERIFY_MEM") != nullptr; // ignore register-only differences
        if (!diff.empty() && (!s_memOnly || memDiff))
        {
            ++s_bad;
            if (s_reports < 60)
            {
                ++s_reports;
                std::printf("[vu1-verify] %016llx entry=%04x (%llu/%llu bad)%s\n", static_cast<unsigned long long>(hash), entry,
                            static_cast<unsigned long long>(s_bad), static_cast<unsigned long long>(s_checked), diff.c_str());
                std::fflush(stdout);
            }
        }
        return true;
    }
}

void VU1Interpreter::execute(uint8_t *vuCode, uint32_t codeSize,
                             uint8_t *vuData, uint32_t dataSize,
                             GS &gs, PS2Memory *memory,
                             uint32_t startPC, uint32_t top, uint32_t itop,
                             uint32_t maxCycles)
{
    resetScheduler();
    m_state.pc = startPC & microAddressMask();
    g_vuTraceProgramStart = m_state.pc;
    if (m_unit == Unit::VU1 && memory)
        noteVu1Program(vuCode, codeSize, memory->getVU1CodeGeneration(), m_state.pc);
    if (g_vuTracePc == 0xFFFFFFFFu)
    {
        const char *t = std::getenv("PS2X_VU1_TRACE_PC");
        g_vuTracePc = t ? static_cast<uint32_t>(std::strtoul(t, nullptr, 16)) : 0xFFFFFFFEu;
    }
    if (m_unit == Unit::VU1)
        ++g_vuExecCount;
    if (g_vuTraceIndex == -2)
    {
        const char *ti = std::getenv("PS2X_VU1_TRACE_INDEX");
        g_vuTraceIndex = ti ? std::atoll(ti) : -1;
    }
    if (g_vuTraceRemaining < 0 && m_unit == Unit::VU1 &&
        (m_state.pc == g_vuTracePc || static_cast<int64_t>(g_vuExecCount) == g_vuTraceIndex))
    {
        g_vuTraceRemaining = 1500;
        std::printf("[vu1-trace] begin pc=0x%x top=%u itop=%u\n", m_state.pc, top, itop);
        for (int r = 0; r < 32; ++r)
        {
            uint32_t w[4];
            std::memcpy(w, m_state.vf[r], 16);
            std::printf("[vu1-trace]   vf%02d %08x %08x %08x %08x\n", r, w[0], w[1], w[2], w[3]);
        }
        for (int r = 0; r < 16; ++r)
            std::printf("[vu1-trace]   vi%02d %04x\n", r, static_cast<uint32_t>(m_state.vi[r]) & 0xFFFFu);
    }
    m_state.ebit = false;
    m_state.haltAfterDelaySlot = false;
    m_state.stoppedByD = false;
    m_state.stoppedByT = false;
    m_state.top = top;
    m_state.itop = itop;
    m_state.branchPending = false;
    m_state.branchTarget = 0;
    m_state.branchDelay = 0;
    m_state.vf[0][0] = 0.0f;
    m_state.vf[0][1] = 0.0f;
    m_state.vf[0][2] = 0.0f;
    m_state.vf[0][3] = 1.0f;
    if (m_unit == Unit::VU1 && memory && g_vuTraceRemaining < 0)
    {
        if (vu1VerifyNative(m_state, vuData, dataSize, g_vu1CodeHash, maxCycles,
                            [&]() { run(vuCode, codeSize, vuData, dataSize, gs, memory, maxCycles); }))
            return;
        bool ended = false;
        if (ps2vu1nTryRun(m_state, vuData, dataSize, memory, g_vu1CodeHash, maxCycles, ended))
        {
            ++g_vuStatRuns;
            if (ended)
            {
                m_state.ebit = false;
                m_state.haltAfterDelaySlot = false;
                m_state.branchPending = false;
                return;
            }
        }
    }
    run(vuCode, codeSize, vuData, dataSize, gs, memory, maxCycles);
}

void VU1Interpreter::resume(uint8_t *vuCode, uint32_t codeSize,
                            uint8_t *vuData, uint32_t dataSize,
                            GS &gs, PS2Memory *memory,
                            uint32_t top, uint32_t itop, uint32_t maxCycles)
{
    m_state.top = top;
    m_state.itop = itop;
    m_state.stoppedByD = false;
    m_state.stoppedByT = false;
    if (m_unit == Unit::VU1 && memory && g_vuTraceRemaining < 0 && !m_state.branchPending &&
        !m_state.ebit && !m_state.haltAfterDelaySlot && !pipelinesPending())
    {
        // MSCNT: continue where the previous program stopped (RenderWare runs every batch this way).
        noteVu1Program(vuCode, codeSize, memory->getVU1CodeGeneration(), m_state.pc);
        if (vu1VerifyNative(m_state, vuData, dataSize, g_vu1CodeHash, maxCycles,
                            [&]() { run(vuCode, codeSize, vuData, dataSize, gs, memory, maxCycles); }))
            return;
        bool ended = false;
        if (ps2vu1nTryRun(m_state, vuData, dataSize, memory, g_vu1CodeHash, maxCycles, ended))
        {
            ++g_vuStatRuns;
            if (ended)
            {
                m_state.ebit = false;
                m_state.haltAfterDelaySlot = false;
                m_state.branchPending = false;
                return;
            }
        }
    }
    run(vuCode, codeSize, vuData, dataSize, gs, memory, maxCycles);
}

void VU1Interpreter::run(uint8_t *vuCode, uint32_t codeSize,
                         uint8_t *vuData, uint32_t dataSize,
                         GS &gs, PS2Memory *memory, uint32_t maxCycles)
{
    m_activeVuData = vuData;
    m_activeVuDataSize = dataSize;
    m_activeGs = &gs;
    m_activeMemory = memory;

    const int previousRoundingMode = std::fegetround();
    const bool useVuRounding = std::fesetround(FE_TOWARDZERO) == 0;
    const uint64_t budgetEnd = m_cycle + maxCycles;
    const uint64_t statStartCycle = m_cycle;
    bool programEnded = false;
    struct TraceState
    {
        bool active = false;
        uint32_t pc = 0, upper = 0, lower = 0;
        float vf[32][4];
        int32_t vi[16];
    } trace;
    auto flushTrace = [&]()
    {
        if (!trace.active)
            return;
        trace.active = false;
        std::printf("[vu1-trace] %04x: %08x %08x", trace.pc, trace.upper, trace.lower);
        for (int r = 1; r < 32; ++r)
            if (std::memcmp(trace.vf[r], m_state.vf[r], 16) != 0)
            {
                uint32_t w[4];
                std::memcpy(w, m_state.vf[r], 16);
                std::printf(" vf%d=[%08x %08x %08x %08x]", r, w[0], w[1], w[2], w[3]);
                std::memcpy(trace.vf[r], m_state.vf[r], 16);
            }
        for (int r = 1; r < 16; ++r)
            if (trace.vi[r] != m_state.vi[r])
                std::printf(" vi%d=%04x", r, static_cast<uint32_t>(m_state.vi[r]) & 0xFFFFu);
        std::printf("\n");
        if (--g_vuTraceRemaining == 0)
            std::printf("[vu1-trace] end\n");
    };
    while (m_cycle < budgetEnd && !m_stopRequested)
    {
        commitReadyPipelines();
        flushTrace();
        if (m_state.pc + 8u > codeSize)
            break;

        const DecodedInstructionPair decoded = getDecodedInstructionPairForPc(vuCode, codeSize, memory, m_state.pc);
        float traceBefore[32][4];
        int32_t traceViBefore[16];
        const bool tracing = g_vuTraceRemaining > 0 && m_unit == Unit::VU1;
        const uint32_t tracePc = m_state.pc;
        if (tracing)
        {
            std::memcpy(traceBefore, m_state.vf, sizeof(traceBefore));
            for (int r = 0; r < 16; ++r)
                traceViBefore[r] = m_state.vi[r];
        }
        if (decoded.upperUsage.reserved || decoded.lowerUsage.reserved)
        {
            reportReservedInstruction(decoded.upperUsage.reserved, decoded.upperUsage.reserved ? decoded.upper : decoded.lower);
            break;
        }

        uint64_t readyCycle = calculatePairReadyCycle(decoded);
        while (readyCycle > m_cycle)
        {
            if (readyCycle >= budgetEnd)
            {
                advanceTo(budgetEnd);
                break;
            }
            advanceTo(readyCycle);
            readyCycle = calculatePairReadyCycle(decoded);
        }
        if (m_cycle >= budgetEnd)
        {
            ++g_vuStatBudgetHits;
            break;
        }
        ++g_vuStatPairs;

        uint8_t writtenVi = 0u;
        int32_t oldVi = 0;
        for (uint32_t reg = 1; reg < 16u; ++reg)
        {
            if ((decoded.lowerUsage.viWrite & (1u << reg)) != 0u)
            {
                writtenVi = static_cast<uint8_t>(reg);
                oldVi = m_state.vi[reg];
                break;
            }
        }

        const VfAccess upperWrite = decoded.upperUsage.vfWrite;
        const VfAccess lowerWrite = decoded.lowerUsage.vfWrite;
        const bool hasUpperWrite = upperWrite.reg != 0u;
        const bool hasLowerWrite = lowerWrite.reg != 0u && decoded.suppressedLowerVf != lowerWrite.reg;
        const bool hasDistinctLowerWrite = hasLowerWrite && (!hasUpperWrite || lowerWrite.reg != upperWrite.reg);
        float oldUpperVf[4]{};
        float newUpperVf[4]{};
        float oldLowerVf[4]{};
        float newLowerVf[4]{};
        float oldAcc[4]{};
        float newAcc[4]{};
        if (hasUpperWrite)
            std::memcpy(oldUpperVf, m_state.vf[upperWrite.reg], sizeof(oldUpperVf));
        if (hasDistinctLowerWrite)
            std::memcpy(oldLowerVf, m_state.vf[lowerWrite.reg], sizeof(oldLowerVf));
        if (decoded.upperUsage.accWrite != 0u)
            std::memcpy(oldAcc, m_state.acc, sizeof(oldAcc));

        if (decoded.iBit)
        {
            execUpper(decoded.upper);
            float immediate = 0.0f;
            std::memcpy(&immediate, &decoded.lower, sizeof(immediate));
            m_state.i = immediate; // raw bits: microcode loads integer constants via LOI
        }
        else if (decoded.upperVfShadowReg != 0u)
        {
            float oldVf[4]{};
            float upperVf[4]{};
            std::memcpy(oldVf,
                        m_state.vf[decoded.upperVfShadowReg],
                        sizeof(oldVf));
            execUpper(decoded.upper);
            std::memcpy(upperVf,
                        m_state.vf[decoded.upperVfShadowReg],
                        sizeof(upperVf));
            std::memcpy(m_state.vf[decoded.upperVfShadowReg],
                        oldVf,
                        sizeof(oldVf));
            execLower(decoded.lower, vuData, dataSize, gs, memory, decoded.upper);
            std::memcpy(m_state.vf[decoded.upperVfShadowReg],
                        upperVf,
                        sizeof(upperVf));
        }
        else
        {
            execUpper(decoded.upper);
            execLower(decoded.lower, vuData, dataSize, gs, memory, decoded.upper);
        }

        m_viBranchBackupValid = false;
        if (tracing)
        {
            trace.active = true;
            trace.pc = tracePc;
            trace.upper = decoded.upper;
            trace.lower = decoded.lower;
            std::memcpy(trace.vf, traceBefore, sizeof(traceBefore));
            std::memcpy(trace.vi, traceViBefore, sizeof(traceViBefore));
        }

        if (hasUpperWrite)
        {
            std::memcpy(newUpperVf, m_state.vf[upperWrite.reg], sizeof(newUpperVf));
            std::memcpy(m_state.vf[upperWrite.reg], oldUpperVf, sizeof(oldUpperVf));
            const uint32_t latency =
                decoded.upperUsage.vfLatency != 0u
                    ? decoded.upperUsage.vfLatency
                    : decoded.upperUsage.latency;
            queueVfWrite(upperWrite.reg, upperWrite.lanes, newUpperVf, latency);
        }
        if (hasDistinctLowerWrite)
        {
            std::memcpy(newLowerVf, m_state.vf[lowerWrite.reg], sizeof(newLowerVf));
            std::memcpy(m_state.vf[lowerWrite.reg], oldLowerVf, sizeof(oldLowerVf));
            const uint32_t latency = decoded.lowerUsage.vfLatency != 0u
                                         ? decoded.lowerUsage.vfLatency
                                         : decoded.lowerUsage.latency;
            queueVfWrite(lowerWrite.reg, lowerWrite.lanes, newLowerVf, latency);
        }
        if (decoded.upperUsage.accWrite != 0u)
        {
            std::memcpy(newAcc, m_state.acc, sizeof(newAcc));
            std::memcpy(m_state.acc, oldAcc, sizeof(oldAcc));
            // ACC is forwarded to the next upper instruction. Its arithmetic
            // flags still use the normal four-cycle FMAC timeline.
            queueAccWrite(decoded.upperUsage.accWrite, newAcc,
                          kAccForwardLatency);
        }
        if (writtenVi != 0u)
        {
            const int32_t newVi = m_state.vi[writtenVi];
            m_state.vi[writtenVi] = oldVi;
            const uint32_t latency =
                decoded.lowerUsage.viLatency != 0u
                    ? decoded.lowerUsage.viLatency
                    : decoded.lowerUsage.latency;
            queueViWrite(writtenVi, newVi, latency);
        }

        markPairWrites(decoded);
        if (writtenVi != 0u && decoded.lowerUsage.delaysNextBranchRead)
            recordViWriteForBranch(writtenVi, oldVi);

        m_state.vf[0][0] = 0.0f;
        m_state.vf[0][1] = 0.0f;
        m_state.vf[0][2] = 0.0f;
        m_state.vf[0][3] = 1.0f;
        m_state.vi[0] = 0;

        uint32_t nextPc = m_state.pc + 8u;
        if (nextPc >= codeSize)
            nextPc = 0u;
        m_state.pc = nextPc;

        if (m_state.branchPending)
        {
            if (m_state.branchDelay == 0u)
            {
                m_state.pc = m_state.branchTarget & microAddressMask();
                m_state.branchPending = false;
            }
            else
            {
                --m_state.branchDelay;
            }
        }

        const bool dHalt = decoded.dBit && m_state.dBitEnabled;
        const bool tHalt = decoded.tBit && m_state.tBitEnabled;
        const bool haltBit = dHalt || tHalt;
        const bool haltBranch = haltBit && decoded.lowerUsage.pipeline == PipelineBranch;

        if (m_state.haltAfterDelaySlot)
        {
            m_state.stoppedByD = m_pendingHaltD;
            m_state.stoppedByT = m_pendingHaltT;
            programEnded = true;
        }
        else if (m_state.ebit)
            programEnded = true;
        else if (haltBit && !haltBranch)
        {
            m_state.stoppedByD = dHalt;
            m_state.stoppedByT = tHalt;
            programEnded = true;
        }
        else if (decoded.eBit)
            m_state.ebit = true;
        else if (haltBranch)
        {
            m_state.haltAfterDelaySlot = true;
            m_pendingHaltD = dHalt;
            m_pendingHaltT = tHalt;
        }

        advanceOneCycle();
        if (programEnded)
            break;
    }

    if (programEnded)
    {
        flushPipelines();
        m_state.ebit = false;
        m_state.haltAfterDelaySlot = false;
        m_pendingHaltD = false;
        m_pendingHaltT = false;
    }
    m_state.cycles = m_cycle;
    if (m_unit == Unit::VU1)
    {
        static const bool s_stats = std::getenv("PS2X_VU_STATS") != nullptr;
        ++g_vuStatRuns;
        g_vuStatCycles += m_cycle - statStartCycle;
        static auto s_last = std::chrono::steady_clock::now();
        const auto now = std::chrono::steady_clock::now();
        if (s_stats && now - s_last >= std::chrono::seconds(2))
        {
            s_last = now;
            std::printf("[vu-stats] runs=%llu pairs=%llu cycles=%llu budgetHits=%llu maxCycles=%u codeChanges=%llu native=%llu fallback=%llu miss=%llu ncyc=%llu hash=%016llx\n",
                        (unsigned long long)g_vuStatRuns, (unsigned long long)g_vuStatPairs,
                        (unsigned long long)g_vuStatCycles, (unsigned long long)g_vuStatBudgetHits, maxCycles,
                        (unsigned long long)g_vu1HashChanges, (unsigned long long)ps2vu1n::g_nativeRuns,
                        (unsigned long long)ps2vu1n::g_nativeFallbacks, (unsigned long long)ps2vu1n::g_nativeMisses,
                        (unsigned long long)ps2vu1n::g_nativeCycles,
                        (unsigned long long)g_vu1CodeHash);
            g_vu1HashChanges = 0;
            ps2vu1n::g_nativeRuns = ps2vu1n::g_nativeFallbacks = ps2vu1n::g_nativeMisses = ps2vu1n::g_nativeCycles = 0;
            g_vuStatRuns = g_vuStatPairs = g_vuStatCycles = g_vuStatBudgetHits = 0;
        }
    }
    if (useVuRounding && previousRoundingMode != -1)
        std::fesetround(previousRoundingMode);
}
